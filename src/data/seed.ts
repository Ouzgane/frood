/** Date ISO à J+days, heure h:m (heure locale). */
const at = (days: number, h: number, m = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(h, m, 0, 0);
  return d.toISOString();
};

